BEGIN;

-- Required to prevent overlapping confirmed room bookings.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Drop child tables first so the script can be rerun.
DROP TABLE IF EXISTS check_in_check_out CASCADE;
DROP TABLE IF EXISTS payment CASCADE;
DROP TABLE IF EXISTS booking CASCADE;
DROP TABLE IF EXISTS room CASCADE;
DROP TABLE IF EXISTS guest CASCADE;

-- 1. Guest details
CREATE TABLE guest (
    guest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20),
    email VARCHAR(254) UNIQUE,
    address VARCHAR(200),
    date_registered DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT chk_guest_name_not_blank
        CHECK (length(trim(full_name)) > 0)
);

-- 2. Room details
CREATE TABLE room (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL UNIQUE,
    room_type VARCHAR(50) NOT NULL,
    rate_per_night NUMERIC(10,2) NOT NULL
        CHECK (rate_per_night >= 0),
    room_status VARCHAR(20) NOT NULL DEFAULT 'Available',
    CONSTRAINT chk_room_status
        CHECK (room_status IN (
            'Available', 'Occupied', 'Maintenance', 'Out of Service'
        )),
    CONSTRAINT chk_room_number_not_blank
        CHECK (length(trim(room_number)) > 0)
);

-- 3. Reservations linking guests and rooms
CREATE TABLE booking (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id BIGINT NOT NULL REFERENCES guest(guest_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    room_id BIGINT NOT NULL REFERENCES room(room_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    booking_date DATE NOT NULL DEFAULT CURRENT_DATE,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    number_of_guests INTEGER NOT NULL DEFAULT 1,
    booking_status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    CONSTRAINT chk_booking_dates
        CHECK (check_out_date > check_in_date),
    CONSTRAINT chk_booking_guest_count
        CHECK (number_of_guests >= 1),
    CONSTRAINT chk_booking_status
        CHECK (booking_status IN (
            'Pending', 'Confirmed', 'Cancelled', 'Completed'
        ))
);

-- Prevent overlapping confirmed bookings for the same room.
-- Check-out date is exclusive.
ALTER TABLE booking
    ADD CONSTRAINT ex_room_confirmed_booking_no_overlap
    EXCLUDE USING gist (
        room_id WITH =,
        daterange(check_in_date, check_out_date, '[)') WITH &&
    )
    WHERE (booking_status = 'Confirmed');

-- 4. Payments associated with bookings
CREATE TABLE payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking(booking_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(50) NOT NULL,
    transaction_reference VARCHAR(100) UNIQUE,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    CONSTRAINT chk_payment_method_not_blank
        CHECK (length(trim(payment_method)) > 0),
    CONSTRAINT chk_payment_status
        CHECK (payment_status IN (
            'Pending', 'Successful', 'Failed', 'Refunded'
        ))
);

-- 5. Actual check-in and check-out records
CREATE TABLE check_in_check_out (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES booking(booking_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    actual_check_in TIMESTAMP,
    actual_check_out TIMESTAMP,
    staff_name VARCHAR(100) NOT NULL,
    CONSTRAINT chk_checkin_checkout_order
        CHECK (
            actual_check_in IS NULL
            OR actual_check_out IS NULL
            OR actual_check_out >= actual_check_in
        ),
    CONSTRAINT chk_staff_name_not_blank
        CHECK (length(trim(staff_name)) > 0)
);

-- Save the schema changes.
COMMIT;

